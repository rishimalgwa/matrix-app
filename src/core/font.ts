const cache35 = new Map<string, number[]>();
function parse35(rows: string) {
  const r = rows.split(",");
  const w = r[0].length;
  const cols: number[] = [];
  for (let x = 0; x < w; x++) {
    let m = 0;
    for (let y = 0; y < r.length; y++) if (r[y][x] === "#") m |= 1 << y;
    cols.push(m);
  }
  return cols;
}

export const FONT_3x5: BitmapFont = {
  id: "3x5",
  name: "3×5 Tiny",
  height: 5,
  glyph(ch) {
    const key = T35[ch] ? ch : T35[ch.toUpperCase()] ? ch.toUpperCase() : "?";
    let g = cache35.get(key);
    if (!g) { g = parse35(T35[key]); cache35.set(key, g); }
    return g;
  },
};

export const FONTS = [FONT_5x7, FONT_3x5];
export const fontById = (id: string) => FONTS.find((f) => f.id === id) ?? FONT_5x7;

/** Renders a string into a strip of column bitmasks. */
export function renderText(text: string, font: BitmapFont, spacing = 1): number[] {
  const cols: number[] = [];
  const chars = Array.from(text);
  chars.forEach((ch, i) => {
    cols.push(...font.glyph(ch));
    if (i < chars.length - 1) for (let s = 0; s < spacing; s++) cols.push(0);
  });
  return cols;
}

export const textWidth = (text: string, font: BitmapFont, spacing = 1) => renderText(text, font, spacing).length;

/** Stamps column bitmap into a frame at (x, y). */
export function stamp(
  frame: number[],
  cols: number[],
  x: number,
  y: number,
  color: number | ((col: number, row: number) => number),
  frameW = 16,
  frameH = 16
) {
  for (let i = 0; i < cols.length; i++) {
    const px = x + i;
    if (px < 0 || px >= frameW) continue;
    const m = cols[i];
    for (let r = 0; m >> r; r++) {
      if (!((m >> r) & 1)) continue;
      const py = y + r;
      if (py < 0 || py >= frameH) continue;
      frame[py * frameW + px] = typeof color === "function" ? color(px, py) : color;
    }
  }
}
