const EXTRA57: Record<string, number[]> = {
  "♥": [0x0C, 0x1E, 0x3C, 0x1E, 0x0C],
  "°": [0x00, 0x06, 0x09, 0x09, 0x06],
  "★": [0x24, 0x1C, 0x0F, 0x1C, 0x24],
  "♪": [0x60, 0x70, 0x3F, 0x02, 0x04],
};

/** Strips empty leading/trailing columns so text is tighter (keeps ≥1 col). */
function trim(cols: number[]) {
  let a = 0, b = cols.length;
  while (a < b - 1 && cols[a] === 0) a++;
  while (b > a + 1 && cols[b - 1] === 0) b--;
  return cols.slice(a, b);
}

export const FONT_5x7: BitmapFont = {
  id: "5x7",
  name: "5×7 Classic",
  height: 7,
  glyph(ch) {
    if (ch === " ") return [0, 0, 0];
    if (EXTRA57[ch]) return EXTRA57[ch];
    const code = ch.charCodeAt(0);
    if (code < 0x20 || code > 0x7e) return EXTRA57["★"];
    const o = (code - 0x20) * 5;
    return trim(F57.slice(o, o + 5));
  },
};

